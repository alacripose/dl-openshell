"""Generate the OpenLock shell's copy of the Popit Forge colour pairs.

    python tools/gen_popit_pairs.py           # write the generated files
    python tools/gen_popit_pairs.py --check   # exit 1 when a generated file is stale

`shell/alpha-shell/popit-pairs.json` is the single source. It is a copy of the
Popit Forge data (`popit-blender/design/popit-pairs.json`, itself read from the
Imagisphere player-colour tables), with the game each pair shipped in and the
wiki revision it came from. Nothing hand-copies a hex value: the parity gate
runs `--check`, so the JS table and the CSS rules cannot drift from the data.

Generated:
  clientaddon/panorama/scripts/openlock_pairs.js   the 37-pair table
  clientaddon/panorama/styles/openlock_pairs.css   one .Pair<Id> block per pair

The CSS is a skin, not a second palette: a pair writes the Popit slab, its
title, its active tool and its emphasis ink. The shell's ground, ink and single
selection accent are not in the preimage, so a light pair cannot turn the shell
into a highlighter. Classic mode drops the pair class and the scheme returns.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "shell" / "alpha-shell" / "popit-pairs.json"
JS_OUT = ROOT / "clientaddon" / "panorama" / "scripts" / "openlock_pairs.js"
CSS_OUT = ROOT / "clientaddon" / "panorama" / "styles" / "openlock_pairs.css"

FORMAT = "openlock.popit-pairs/3080abf5e17bdee04de3bc0b0b5d43ab"
SLUG = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")
ROLES = ("primary", "secondary", "tertiary", "emphasis")

HEADER = "/* Generated by tools/gen_popit_pairs.py from shell/alpha-shell/popit-pairs.json. */"


class PairRefusal(ValueError):
    """The data file is wrong; the generator refuses instead of guessing."""


def load(path: Path = DATA) -> dict:
    if not path.is_file():
        raise PairRefusal(f"data-missing: {path.relative_to(ROOT)}")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise PairRefusal(f"data-unreadable: {path.relative_to(ROOT)}:{error.lineno}") from error
    if data.get("format") != FORMAT:
        raise PairRefusal(f"format-mismatch: expected {FORMAT}, found {data.get('format')!r}")
    pairs = data.get("pairs")
    if not isinstance(pairs, list) or not pairs:
        raise PairRefusal("pairs-missing: the data file declares no pairs")
    seen: set[str] = set()
    for index, pair in enumerate(pairs, 1):
        pair_id = str(pair.get("id") or "")
        if not SLUG.match(pair_id):
            raise PairRefusal(f"pair-id: entry {index} id {pair_id!r} is not a lowercase slug")
        if pair_id in seen:
            raise PairRefusal(f"pair-duplicate: {pair_id!r} appears twice")
        seen.add(pair_id)
        for role in ROLES:
            value = str(pair.get(role) or "")
            if not HEX.match(value):
                raise PairRefusal(f"pair-colour: {pair_id}.{role} {value!r} is not #RRGGBB")
        if not str(pair.get("name") or "").strip():
            raise PairRefusal(f"pair-name: {pair_id} has no name")
    default = str(data.get("default") or "")
    if default not in seen:
        raise PairRefusal(f"default-missing: {default!r} is not one of the pairs")
    return data


def contrast_ink(colour: str) -> str:
    """Dark ink on light slabs, the warm ink on dark ones, from the primary."""
    hex_value = colour.lstrip("#")
    red, green, blue = (int(hex_value[index : index + 2], 16) / 255.0 for index in (0, 2, 4))
    luminance = 0.2126 * red + 0.7152 * green + 0.0722 * blue
    return "#10131a" if luminance > 0.55 else "#f4f2ea"


def _channels(colour: str) -> tuple[int, int, int]:
    value = colour.lstrip("#")
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def shade(colour: str, factor: float) -> str:
    """`_shade` from the Popit Forge prototype's `popit_ui/theme.py`."""
    return "".join(f"{max(0, min(255, round(c * factor))):02x}" for c in _channels(colour)).upper()


def mix(colour: str, other: str, amount: float) -> str:
    """`_mix` from the Popit Forge prototype's `popit_ui/theme.py`."""
    a = _channels(colour)
    b = _channels(other)
    return "".join(
        f"{max(0, min(255, round(x + (y - x) * amount))):02x}" for x, y in zip(a, b)
    ).upper()


def pair_class(pair_id: str) -> str:
    """Keep this identical to pairClass() in openlock_popit.js."""
    words = re.split(r"[-_]", pair_id)
    return "Pair" + "".join(word[:1].upper() + word[1:] for word in words if word)


def css(data: dict) -> str:
    lines = [
        HEADER,
        "/* Edit shell/alpha-shell/popit-pairs.json, not this file.",
        "   One block per pair. A block paints only the Popit slab, title, active tool,",
        "   selected row and emphasis ink; the shell ground and selection accent stay put.",
        "   Classic mode removes the Pair class and the scheme's own roles return. */",
        "",
    ]
    for pair in data["pairs"]:
        klass = pair_class(pair["id"])
        primary = pair["primary"]
        secondary = pair["secondary"]
        tertiary = pair["tertiary"]
        emphasis = pair["emphasis"]
        ink = contrast_ink(primary)
        lines.append(f"/* {pair['name']} — {pair['game']} */")
        # LBP3's role map, from the design bible: secondary is the menu background, primary is
        # the highlight/tooltip/ownership accent, tertiary is the menu accent and emphasis is
        # emphasised text. Painting the slab from primary would invert the shipped roles.
        lines.append(f".{klass} .PopitRoot {{ background-color: {secondary}E6; border-color: {primary}; }}")
        lines.append(f".{klass} .PopitChild {{ background-color: {secondary}E6; border-color: {primary}; }}")
        lines.append(f".{klass} .PopitHeaderTitle {{ color: {tertiary}; }}")
        lines.append(f".{klass} .PopitWordmark {{ color: {tertiary}; }}")
        lines.append(f".{klass} .PopitPairChip {{ background-color: {primary}33; border-color: {primary}; }}")
        lines.append(f".{klass} .PopitPairChipLabel {{ color: {ink}; }}")
        lines.append(f".{klass} .PopitRootRow.Active {{ background-color: {primary}33; border-color: {primary}; }}")
        lines.append(f".{klass} .PopitTool.Active {{ background-color: {primary}; border-color: {tertiary}; }}")
        lines.append(f".{klass} .PopitOption.Selected {{ background-color: {primary}; border-color: {tertiary}; }}")
        lines.append(f".{klass} .PopitPageDot.On {{ background-color: {primary}; }}")
        lines.append(f".{klass} .PopitItem.Selected {{ border-color: {primary}; }}")
        lines.append(f".{klass} .PopitTarget.Selected {{ border-color: {primary}; }}")
        lines.append(f".{klass} .PopitDetail {{ color: {emphasis}; }}")
        # The live shell uses the same slot map the Popit Forge prototype writes into a live
        # theme (`popit_ui/theme.py: pair_slots`): the primary shades the surface, the secondary
        # carries the header and the outline, the tertiary is the title ink, and a quarter-white
        # mix of the primary is the cell edge. The transforms are copied, not re-chosen, so one
        # selection mechanism paints both the Popit and the window manager.
        lines.append(
            f".{klass} .WindowFrame {{ background-color: #{shade(primary, 0.42)}; "
            f"border-color: {secondary}; }}"
        )
        lines.append(
            f".{klass} .WindowFrame.CompactHud {{ background-color: transparent; "
            f"border-color: {secondary}; }}"
        )
        lines.append(
            f".{klass} .WindowFrame .WindowTitle {{ background-color: #{shade(secondary, 0.60)}; }}"
        )
        lines.append(f".{klass} .WindowFrame .WindowTitleLabel {{ color: {tertiary}; }}")
        lines.append(
            f".{klass} .ThemedCell {{ border-color: #{mix(primary, '#ffffff', 0.25)}59; }}"
        )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def js(data: dict) -> str:
    rows = []
    for pair in data["pairs"]:
        rows.append(
            "  {id: %s, name: %s, game: %s, primary: %s, secondary: %s, tertiary: %s, "
            "emphasis: %s, ink: %s},"
            % (
                json.dumps(pair["id"]),
                json.dumps(pair["name"]),
                json.dumps(pair["game"]),
                json.dumps(pair["primary"]),
                json.dumps(pair["secondary"]),
                json.dumps(pair["tertiary"]),
                json.dumps(pair["emphasis"]),
                json.dumps(contrast_ink(pair["primary"])),
            )
        )
    return (
        "// Generated by tools/gen_popit_pairs.py from shell/alpha-shell/popit-pairs.json.\n"
        "// Edit the data file, not this table. Classic mode removes the Pair class.\n"
        "(function () {\n"
        "    globalThis.OpenlockPopitPairs = {\n"
        '        format: %s,\n'
        '        default: %s,\n'
        "        pairs: [\n%s\n        ]\n"
        "    };\n"
        "})();\n"
        % (json.dumps(FORMAT), json.dumps(data["default"]), "\n".join(rows))
    )


def build() -> dict[Path, str]:
    data = load()
    return {JS_OUT: js(data), CSS_OUT: css(data)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    args = parser.parse_args(argv)
    try:
        files = build()
    except PairRefusal as refusal:
        print(f"REFUSED {refusal}")
        return 2
    stale = []
    for path, text in files.items():
        if args.check:
            current = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != text:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    data = load()
    if args.check:
        for name in stale:
            print(f"stale {name}")
        print(f"pairs: {len(files)} generated files {'stale' if stale else 'current'}")
        return 1 if stale else 0
    print(f"pairs: wrote {len(files)} files for {len(data['pairs'])} pairs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
