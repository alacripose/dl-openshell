#!/usr/bin/env python3
"""Generate the Panorama shell's contour data from the family's measured shape.

The shape is `docs/contour.json`, the same page 9 profile `popit-shell` draws, and
`docs/family-look.json` is the pin: the accepted corner, the pads, the stroke and the surfaces
that must carry it. Panorama has no `clip-path`, so the shell draws the silhouette as nine
slices: the corner bands are rows whose widths come from the profile, and the middle takes the
span. A row is one pixel high and never scaled, so no part of the shape stretches.

This tool writes `clientaddon/panorama/scripts/openlock_contour_data.js`. The runtime
(`openlock_contour.js`) samples the profile again per surface, because the corner band shrinks
on a short surface such as a taskbar button, and the gate (`tools/contour_gate.py`) refuses a
stale data file, a stretched slice and a rounded rectangle standing in for the contour.

    python tools/gen_contour_slices.py            # write the data file
    python tools/gen_contour_slices.py --check    # exit 1 when it is stale
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTOUR = ROOT / "docs" / "contour.json"
LOOK = ROOT / "docs" / "family-look.json"
OUTPUT = ROOT / "clientaddon" / "panorama" / "scripts" / "openlock_contour_data.js"

HEADER = """// Generated by tools/gen_contour_slices.py from docs/contour.json and docs/family-look.json.
// A surface draws this profile as nine slices: fixed one pixel rows at the crowns, the span in
// the middle. Edit the measured shape or the pin, never this file.
"""


def digest(*paths: Path) -> str:
    sha = hashlib.sha256()
    for path in paths:
        sha.update(path.read_bytes())
    return sha.hexdigest()


def build() -> str:
    contour = json.loads(CONTOUR.read_text(encoding="utf-8"))
    look = json.loads(LOOK.read_text(encoding="utf-8"))
    segments = contour["segments"]
    if len(segments) != 8:
        raise SystemExit(f"contour-refused: {len(segments)} segments, the family profile is eight")
    for segment in segments:
        # Two control points and the end point: the start is the previous segment's end.
        if len(segment) != 6:
            raise SystemExit("contour-refused: a segment is not one cubic")
    corner = look["corner_px"]
    if corner["width"] > corner["height"]:
        raise SystemExit("contour-refused: the corner is wider than it is tall")
    units_w = round(contour["right"] - contour["left"], 6)
    units_h = round(contour["bottom"] - contour["top"], 6)
    band_x = round(contour["start"][0] - contour["left"], 6)
    # The corner's depth along the rail: the bottom edge down to where the crown's cubic ends.
    band_y = round(contour["bottom"] - segments[1][5], 6)
    data = {
        "schema": "openlock.contour/1",
        "source": contour["source"],
        "digest": digest(CONTOUR, LOOK),
        "units": {"width": units_w, "height": units_h},
        "box": {key: contour[key] for key in ("left", "right", "top", "bottom")},
        "start": contour["start"],
        "segments": segments,
        "band": {"x": band_x, "y": band_y},
        "look": look,
    }
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return HEADER + "var OpenlockContourData = " + body + ";\n"


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    text = build()
    if "--check" in args:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("[FAIL] contour-stale: openlock_contour_data.js is not this shape")
            return 1
        print("[ok] the Panorama contour data is this shape")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
