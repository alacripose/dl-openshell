#!/usr/bin/env python3
"""Export the Impeccable CUA driver window as a split, digest-verified client bundle.

The shape follows ``examples/motd-addon/build.py``: read the declared sources, stage them, write a
verifiable record, copy into the named target, and refuse if what landed does not hash to what was
built. It is not a Panorama package, so there is no SHPKG frame and no VPK here; the artifact is the
four source files plus ``manifest.json`` that ``secure-shell``'s axis serves at ``/``.

Usage:
    python build.py
    python build.py --target ../secure-shell/client/cua
    python build.py --no-install

Exit status is 0 only when every readback digest matches the staged file and the manifest names every
region this bundle draws.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SOURCE = HERE / "src"
DEFAULT_TARGET = Path(os.environ.get("SECURE_SHELL_CLIENT", ROOT.parent / "secure-shell" / "client" / "cua"))

SCHEMA = "openlock.cua-client/9d35178a82c4bf0c0cc46c87f793d2e4"
NAME = "impeccable-cua-driver"
FILES = ("index.html", "styles.css", "app.js")
REGIONS = (
    "brand-row", "rail", "fleet", "chat", "activity", "composer", "footer",
    "drawer", "apps-launcher", "register-dialog",
)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def stamp_for(relative: str, body: bytes) -> bytes:
    """A generated file says which generator wrote it; the source does not carry that line."""
    note = (
        f"generated by openlock/examples/cua-client/build.py from src/{relative}; "
        "edit the source, not this copy"
    )
    if relative.endswith(".html"):
        marker = b"<!doctype html>\n"
        if body.startswith(marker):
            return marker + b"<!-- " + note.encode("utf-8") + b" -->\n" + body[len(marker):]
        return b"<!-- " + note.encode("utf-8") + b" -->\n" + body
    if relative.endswith(".css"):
        return b"/* " + note.encode("utf-8") + b" */\n" + body
    return b"/* " + note.encode("utf-8") + b" */\n" + body


def generated_at() -> str:
    raw = os.environ.get("SOURCE_DATE_EPOCH", "").strip()
    if not raw:
        return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    try:
        return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(int(raw)))
    except ValueError:
        raise SystemExit(f"refused: SOURCE_DATE_EPOCH: {raw!r} is not an integer epoch")


def read_version() -> str:
    path = SOURCE / "version.txt"
    if not path.is_file():
        raise SystemExit(f"refused: version-missing: {path}")
    version = path.read_text(encoding="utf-8").strip()
    if not version or any(ch.isspace() for ch in version):
        raise SystemExit(f"refused: version-invalid: {version!r}")
    return version


def source_digest() -> str:
    digest = hashlib.sha256()
    for relative in FILES + ("version.txt",):
        path = SOURCE / relative
        if not path.is_file():
            raise SystemExit(f"refused: source-missing: {path}")
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return "sha256:" + digest.hexdigest()


def build(target: Path, version: str, install: bool) -> int:
    stage = ROOT / "dist" / "cua-client"
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)

    records = []
    for relative in FILES:
        body = stamp_for(relative, (SOURCE / relative).read_bytes())
        (stage / relative).write_bytes(body)
        records.append({"path": relative, "bytes": len(body), "sha256": "sha256:" + sha256(body)})

    # The HTML must actually reference the split files it ships beside; a bundle that forgot one is
    # refused before a target is written.
    html = (stage / "index.html").read_text(encoding="utf-8")
    for required in ("/cua/styles.css", "/cua/app.js", 'id="window"', 'id="apps-launcher"'):
        if required not in html:
            raise SystemExit(f"refused: bundle-incomplete: index.html does not carry {required!r}")
    for region in REGIONS:
        if region not in html:
            raise SystemExit(f"refused: region-missing: {region}")

    digest = hashlib.sha256()
    for record in records:
        digest.update(record["path"].encode("utf-8"))
        digest.update(b"\0")
        digest.update((stage / record["path"]).read_bytes())
        digest.update(b"\0")

    manifest = {
        "schema": SCHEMA,
        "name": NAME,
        "version": version,
        "generator": "openlock/examples/cua-client/build.py",
        "builtAt": generated_at(),
        "sourceDigest": source_digest(),
        "digest": "sha256:" + digest.hexdigest(),
        "regions": list(REGIONS),
        "files": records,
    }
    manifest_path = stage / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    print(f"stage     {stage}")
    for record in records:
        print(f"file      {record['path']}  {record['bytes']} bytes  {record['sha256']}")
    print(f"manifest  {manifest_path}  version {version}  {manifest['digest']}")
    print(f"source    {manifest['sourceDigest']}")

    if not install:
        print("installed (not installed: --no-install)")
        print("RESULT: PRESENT (staged)")
        return 0

    target = target.resolve()
    target.mkdir(parents=True, exist_ok=True)
    for record in records + [{"path": "manifest.json", "bytes": manifest_path.stat().st_size,
                              "sha256": "sha256:" + sha256(manifest_path.read_bytes())}]:
        source = stage / record["path"]
        destination = target / record["path"]
        shutil.copy2(source, destination)
        landed = destination.read_bytes()
        if sha256(landed) != record["sha256"].split(":", 1)[1]:
            raise SystemExit(f"refused: readback-mismatch: {destination}")
        print(f"installed {destination}  {len(landed)} bytes  {record['sha256']}")

    print(f"target    {target}")
    print("RESULT: PRESENT (installed)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Export the Impeccable CUA client window.")
    parser.add_argument("--target", default=str(DEFAULT_TARGET), help="directory to install the bundle into")
    parser.add_argument("--version", default="", help="override the version in src/version.txt")
    parser.add_argument("--no-install", action="store_true", help="stage and verify, but do not copy")
    args = parser.parse_args()
    version = args.version.strip() or read_version()
    return build(Path(args.target).expanduser(), version, not args.no_install)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BrokenPipeError:
        sys.exit(0)
